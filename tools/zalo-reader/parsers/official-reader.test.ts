import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { randomUUID } from "node:crypto";
import { OFFICIAL_ZALO_GROUPS as GROUPS, initializeCheckpoint, checkpointWindow, commitSource, advanceWatermark,
  selectIncrementalSources, verifiedProcessingReceipt, verifiedGroupIdentity, readerHealth, redactReaderLog } from "../../../lib/zalo-reader/official";
import { officialSourceIdentity, existingOfficialReceipt } from "../../../lib/zalo-reader/official-request";
import { cleanStatusEvent, readerSecretMatches } from "../../../lib/zalo-reader/status-service";
import { OfficialSession, acquireReaderLock } from "../official-runtime";
import { validateOfficialConfig, runOfflineFixture } from "../official-runner";
import { normalizedRoomIdentity } from "../../../lib/zalo-import/room-comparison";
import { importFilters, applyImportFilters } from "../../../lib/zalo-import/filters";

async function main() {
  const hour=3600000, now=Date.UTC(2026,9,31,0), cp=initializeCheckpoint(GROUPS[0].key,now);
  const candidate=(i:number, extra={})=>({markerMessageId:String(i),markerTimestamp:now-hour+i,sourceHash:`hash-${i}`,imageMessageIds:[],videoMessageIds:[],...extra});
  const rooms=Array.from({length:25},(_,i)=>candidate(i));
  rooms.slice(0,10).forEach(room=>commitSource(cp,[room.markerMessageId],room.markerTimestamp,"existing_source"));
  const selected=selectIncrementalSources(rooms,cp,now,10,20);
  assert.deepEqual(selected.rooms.map(room=>room.markerMessageId),rooms.slice(10,20).map(room=>room.markerMessageId));
  assert.equal(selected.messages,10);
  assert.equal(selectIncrementalSources([candidate(26,{warnings:["ROOM_MARKER_MISSING"]})],cp,now,10,20).rooms.length,0);
  const multi=Array.from({length:21},(_,i)=>candidate(30,{sourceHash:`multi-${i}`}));
  assert.equal(selectIncrementalSources(multi,cp,now,10,20).rooms.length,0,"do not split a source across the budget");
  assert.equal(selectIncrementalSources(multi.slice(0,20),cp,now,10,20).messages,1);
  assert.equal(selectIncrementalSources([candidate(31,{markerTimestamp:now-25*hour})],cp,now,10,20).rooms.length,0);
  assert.equal(verifiedProcessingReceipt({ok:true,batchId:"alone"}),null);
  assert.equal(verifiedProcessingReceipt({ok:true,noChanges:true,comparisonStatus:"UNCHANGED"}),"unchanged");
  const failed=initializeCheckpoint(GROUPS[0].key,now);
  const before=failed.processedThroughMs;
  commitSource(failed,["a"],now-hour,"pending_created"); commitSource(failed,["c"],now-1000,"pending_created");
  const observed=[{id:"a",timestamp:now-hour},{id:"b",timestamp:now-hour},{id:"c",timestamp:now-1000}];
  assert.equal(advanceWatermark(failed,observed,true),before,"cannot jump a failure at the same timestamp");
  commitSource(failed,["b"],now-hour,"pending_created"); assert.equal(advanceWatermark(failed,observed,true),now-1000);
  assert.equal(checkpointWindow(failed,now+48*hour).fromMs,now+24*hour,"each cycle is capped at the latest 24 hours even after sleep");
  assert.equal(selectIncrementalSources([candidate(32,{markerTimestamp:now-25*hour})],failed,now+hour,10,20).rooms.length,0,"old unprocessed sources never extend the 24h window");
  assert.throws(()=>verifiedGroupIdentity(GROUPS[1].key,"g1234567890123",true,2,true),/AMBIGUOUS/);
  assert.throws(()=>verifiedGroupIdentity(GROUPS[0].key,"g1234567890123",true,1,true),/UNVERIFIED/);
  const config=JSON.parse(fs.readFileSync("tools/zalo-reader/official.config.json","utf8"));
  assert.equal(validateOfficialConfig(config).enabled,false);
  assert.throws(()=>validateOfficialConfig({...config,groups:[...config.groups,{key:"outside"}]}));
  const room={house_number:"10",address:"Nguyễn Huệ",district:"Quận 1",room_code:"402"};
  const identityInput={groupName:GROUPS[0].name,groupId:GROUPS[0].groupId!,sourceMessageId:"123",sourceRoomKey:normalizedRoomIdentity(room)!,trial:false,runId:randomUUID(),verified:true};
  const identity=officialSourceIdentity(identityInput,room);
  assert.deepEqual(officialSourceIdentity({...identityInput,runId:randomUUID()},room).batchId,identity.batchId,"retry independent of run ID");
  assert.notEqual(officialSourceIdentity({...identityInput,groupName:GROUPS[1].name,groupId:"g1234567890123"},room).batchId,identity.batchId);
  assert.notEqual(officialSourceIdentity({...identityInput,sourceMessageId:"124"},room).batchId,identity.batchId,"new message of same room enters global comparison");
  assert.notEqual(officialSourceIdentity({...identityInput,trial:true},room).pendingId,identity.pendingId);
  const orphanDb={from:()=>{const query:any={select:()=>query,eq:()=>query,maybeSingle:async()=>({data:null}),then:(resolve:any)=>resolve({data:[{id:identity.batchId,parser_result:{}}]})};return query;}};
  await assert.rejects(()=>existingOfficialReceipt(orphanDb,identity,GROUPS[0].name,room),/REQUIRES_REVIEW/);
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),"zalo-official-offline-"));
  try {
    const release=acquireReaderLock(directory); assert.throws(()=>acquireReaderLock(directory),/ALREADY_RUNNING/); release(); acquireReaderLock(directory)();
    const session=new OfficialSession({stateDirectory:directory,trial:false,initialLookbackHours:24,overlapMinutes:15,maxMessages:10,maxRooms:20,maxScrollSteps:200,now:()=>now});
    await session.beginGroup({},GROUPS[0].key,GROUPS[0].name);session.verify(GROUPS[0].groupId!,true,1,"dom_message_id");
    const pair=[candidate(100,{sourceHash:"one",imageMessageIds:["image-a"]}),candidate(100,{sourceHash:"two",imageMessageIds:["image-b"]})];
    session.select(pair);session.accept(pair[0],{ok:true,pendingVersionId:"pending-a",importType:"CREATE"});
    assert.equal(session.active!.checkpoint.receipts["100"],undefined);
    session.accept(pair[1],{ok:true,pendingVersionId:"pending-b",importType:"UPDATE"});
    assert.ok(session.active!.checkpoint.receipts["image-b"]);
    const trial=new OfficialSession({stateDirectory:directory,trial:true,initialLookbackHours:24,overlapMinutes:15,maxMessages:10,maxRooms:20,maxScrollSteps:200,now:()=>now});
    await trial.beginGroup({},GROUPS[0].key,GROUPS[0].name); trial.totalPending=9;
    assert.equal(trial.select(rooms).length,1,"10 trial rooms total across both groups");
    const checkpointBefore=fs.readFileSync(path.join(directory,"checkpoints",`${GROUPS[0].key}.json`),"utf8");
    await trial.finishGroup();
    assert.equal(fs.readFileSync(path.join(directory,"checkpoints",`${GROUPS[0].key}.json`),"utf8"),checkpointBefore,"trial isolated from production checkpoints");
  } finally { fs.rmSync(directory,{recursive:true,force:true}); }
  const status=cleanStatusEvent({runId:randomUUID(),groupKey:GROUPS[0].key,groupName:GROUPS[0].name,groupId:GROUPS[0].groupId,mode:"official",status:"running",startedAt:new Date(now).toISOString(),heartbeatAt:new Date(now).toISOString(),counters:{pending_created:2,token:"private"},errorCode:"https://private.test/token"});
  assert.equal(status.error_code,null);assert.equal((status.counters as any).token,undefined);
  assert.equal(readerHealth({...status},now+3*hour).stale,true);
  assert.equal(redactReaderLog("fetch https://private.test/?token=secret"),"fetch [URL]");
  const oldSecret=process.env.ZALO_READER_INTERNAL_SECRET;process.env.ZALO_READER_INTERNAL_SECRET="offline";
  assert.equal(readerSecretMatches(new Request("http://offline",{headers:{"x-internal-secret":"offline"}})),true);
  assert.equal(readerSecretMatches(new Request("http://offline")),false);
  if(oldSecret===undefined)delete process.env.ZALO_READER_INTERNAL_SECRET;else process.env.ZALO_READER_INTERNAL_SECRET=oldSecret;
  const calls:any[]=[];const query:any={eq:(...args:any[])=>{calls.push(args);return query;},gte:(...args:any[])=>{calls.push(args);return query;},lte:(...args:any[])=>{calls.push(args);return query;}};
  applyImportFilters(query,importFilters({group:GROUPS[0].name,type:"UPDATE",readFrom:"2026-10-30"}));
  assert.equal(calls.length,3);assert.throws(()=>importFilters({group:"unrelated"}));
  const source=fs.readFileSync("lib/zalo-reader/import-service.ts","utf8");
  assert.ok(source.indexOf('if (officialIdentity) {\n      // Keep all')<source.indexOf('let autoPublished = false'));
  const fixture=await runOfflineFixture("tools/zalo-reader/fixtures/official-two-groups.json",process.cwd());
  assert.equal(fixture.summaries.length,2);assert.equal(fixture.summaries[0].counters.pending_created,1);assert.equal(fixture.summaries[1].counters.pending_created,1);
  console.log("Official Reader incremental/identity/lock/status/offline runner: PASS");
}
main().catch(error=>{console.error(error);process.exitCode=1;});
